// 개념 학습 데이터 검증 함수
window.validateConcepts = function (concepts) {
  var list = concepts === undefined ? window.SPELLING_CONCEPTS : concepts;
  var errors = [];
  if (!Array.isArray(list)) {
    return { ok: false, errors: ["SPELLING_CONCEPTS가 배열이 아닙니다."], count: 0 };
  }
  if (list.length !== 9) {
    errors.push("개념 데이터 개수가 " + list.length + "개입니다. (9개여야 함)");
  }
  var seenIds = {};
  var seenCats = {};
  var fields = ["id", "category", "title", "summary", "rules", "comparison", "examples", "tip", "caution"];
  
  for (var i = 0; i < list.length; i++) {
    var c = list[i];
    var tag = "항목 " + (i + 1);
    if (!c || typeof c !== "object") {
      errors.push(tag + ": 객체가 아닙니다.");
      continue;
    }
    for (var j = 0; j < fields.length; j++) {
      var f = fields[j];
      if (!(f in c)) {
        errors.push(tag + " (" + (c.id || "무명") + "): '" + f + "' 속성이 없습니다.");
      }
    }
    if (seenIds[c.id]) { errors.push("id 중복: " + c.id); } else { seenIds[c.id] = true; }
    if (seenCats[c.category]) { errors.push("category 중복: " + c.category); } else { seenCats[c.category] = true; }
    if (!Array.isArray(c.rules) || c.rules.length === 0) {
      errors.push(tag + ": rules가 비어 있거나 배열이 아닙니다.");
    }
    if (!c.examples || !Array.isArray(c.examples.correct) || !Array.isArray(c.examples.incorrect)) {
      errors.push(tag + ": examples 형식이 올바르지 않습니다.");
    }
  }

  // questions.js의 유형과 일치 여부 확인
  if (typeof window.QUESTIONS !== "undefined" && Array.isArray(window.QUESTIONS)) {
    var qCats = {};
    window.QUESTIONS.forEach(function (q) { if (q && q.category) { qCats[q.category] = true; } });
    var qCatKeys = Object.keys(qCats);
    qCatKeys.forEach(function (qc) {
      if (!seenCats[qc]) {
        errors.push("문항 유형 '" + qc + "'에 해당하는 개념 학습 데이터가 없습니다.");
      }
    });
    Object.keys(seenCats).forEach(function (cc) {
      if (!qCats[cc]) {
        errors.push("개념 유형 '" + cc + "'가 문항 데이터의 유형과 일치하지 않습니다.");
      }
    });
  }

  return { ok: errors.length === 0, errors: errors, count: list.length };
};
